/**
 * generate-seo-files.cjs
 *
 * Regenerates the static public/robots.txt and public/sitemap.xml files.
 *
 * Why static files? The production site is a static Vite build on Vercel
 * (no Node server), so the admin panel's /api/seo/* endpoints never run in
 * production and the vercel.json SPA catch-all rewrite sends /robots.txt and
 * /sitemap.xml to index.html (homepage HTML). Static files in public/ are
 * copied to dist/ by Vite and served directly by Vercel, taking precedence
 * over the rewrite.
 *
 * Run: node scripts/generate-seo-files.cjs
 * Run this again whenever blog posts are added/removed or routes change,
 * then commit the regenerated files and redeploy.
 */

const fs = require("fs");
const path = require("path");

const ORIGIN = "https://scribd-downloader-sigma.vercel.app";
const LANGUAGES = ["en", "br", "es", "fr", "de", "id"];
const TODAY = new Date().toISOString().split("T")[0];

// Mirrors buildDynamicSitemapXml() core routes in src/data/siteConfig.ts
const CORE_ROUTES = [
  { path: "", priority: "1.0", changefreq: "daily" },
  { path: "how-it-works", priority: "0.8", changefreq: "weekly" },
  { path: "blog", priority: "0.9", changefreq: "daily" },
  { path: "about", priority: "0.7", changefreq: "monthly" },
  { path: "contact", priority: "0.6", changefreq: "monthly" },
  { path: "privacy", priority: "0.5", changefreq: "monthly" },
  { path: "terms", priority: "0.5", changefreq: "monthly" },
];

const ROOT = path.join(__dirname, "..");
const PUBLIC_DIR = path.join(ROOT, "public");
const BLOG_DATA = path.join(ROOT, "src", "data", "blogData.ts");

function readPublishedPosts() {
  const src = fs.readFileSync(BLOG_DATA, "utf-8");
  const posts = [];
  // Each post is an object literal containing slug/language/status fields.
  const blocks = src.split(/{\s*\n\s*id:/);
  for (const b of blocks) {
    const slug = (b.match(/slug:\s*"([^"]+)"/) || [])[1];
    const language = (b.match(/language:\s*"([^"]+)"/) || [])[1];
    const status = (b.match(/status:\s*"([^"]+)"/) || [])[1];
    if (slug && language && status === "published") {
      posts.push({ slug, language });
    }
  }
  return posts;
}

function urlEntry(loc, lastmod, changefreq, priority) {
  return `  <url>
    <loc>${loc}</loc>
    <lastmod>${lastmod}</lastmod>
    <changefreq>${changefreq}</changefreq>
    <priority>${priority}</priority>
  </url>`;
}

function buildRobotsTxt() {
  // Mirrors buildDefaultRobotsTxt() in src/data/siteConfig.ts
  return `# robots.txt for Scribd Downloader
# Auto-generated by scripts/generate-seo-files.cjs on ${TODAY}

User-agent: *
Allow: /

# Disallow admin control panels and private routes
Disallow: /admin123
Disallow: /admin
Disallow: /admin/*
Disallow: /api/
Disallow: /temp_downloads/

# Sitemap location
Sitemap: ${ORIGIN}/sitemap.xml
`;
}

function buildSitemapXml(posts) {
  const entries = [];

  for (const lang of LANGUAGES) {
    for (const r of CORE_ROUTES) {
      const fullPath = r.path ? `/${lang}/${r.path}` : `/${lang}`;
      entries.push(urlEntry(`${ORIGIN}${fullPath}`, TODAY, r.changefreq, r.priority));
    }
  }

  entries.push(urlEntry(`${ORIGIN}/`, TODAY, "daily", "1.0"));

  for (const post of posts) {
    entries.push(urlEntry(`${ORIGIN}/${post.language}/blog/${post.slug}`, TODAY, "weekly", "0.8"));
  }

  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${entries.join("\n")}
</urlset>`;
}

function main() {
  fs.mkdirSync(PUBLIC_DIR, { recursive: true });
  const posts = readPublishedPosts();

  const robotsPath = path.join(PUBLIC_DIR, "robots.txt");
  const sitemapPath = path.join(PUBLIC_DIR, "sitemap.xml");

  fs.writeFileSync(robotsPath, buildRobotsTxt(), "utf-8");
  fs.writeFileSync(sitemapPath, buildSitemapXml(posts), "utf-8");

  const urlCount = (fs.readFileSync(sitemapPath, "utf-8").match(/<url>/g) || []).length;
  console.log(`Wrote ${robotsPath}`);
  console.log(`Wrote ${sitemapPath} (${urlCount} URLs, ${posts.length} blog posts)`);
}

main();
